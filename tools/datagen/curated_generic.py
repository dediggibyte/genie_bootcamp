"""Coherence hooks for a few *generic* (engine-generated) full-scope tables.

The engine fills these tables from the model, but some columns only make sense together:
a retail store belongs to one retail banner and lies in that banner's country, a POS
record names the store and retailer it references, a contact person's full name matches
the first and last name of the same row. Each hook returns the ``fixed`` values of one row
(plus ``_country`` for the engine's locale); everything else is still generated by the engine.
"""
import datetime
from decimal import Decimal

from . import engine, texts, world

D = Decimal

_STORE_SUFFIX = {
    "SWE": ["Centrum", "City", "Galleria", "Torget", "Hamnen", "Syd", "Nord", "Väst", "Öst"],
    "NOR": ["Sentrum", "Torget", "Brygga", "Syd", "Nord", "Storsenter"],
    "DNK": ["Centrum", "Torvet", "Havnen", "Syd", "Nord", "Storcenter"],
    "FIN": ["Keskusta", "Tori", "Satama", "Itäkeskus", "Länsi"],
    "DEU": ["Zentrum", "Markt", "Hauptbahnhof", "Altstadt", "Nord", "Süd"],
    "NLD": ["Centrum", "Markt", "Station", "Noord", "Zuid"],
    "POL": ["Centrum", "Rynek", "Dworzec", "Północ", "Południe"],
}
_FORMAT = {"grocery": ["supermarket", "supermarket", "hypermarket", "neighbourhood"], "convenience": ["convenience"],
           "discount": ["discount"], "specialty": ["specialty"], "organic": ["specialty"],
           "health_food": ["specialty"], "drugstore": ["drugstore"], "pharmacy": ["pharmacy"]}
_STORES_PER_TIER = {"tier_1_national": 9, "tier_2_regional": 5, "tier_3_local": 3, "tier_4_independent": 1}
_DC_OF_COMPANY = {"SE01": "DCJKG", "NO01": "DCOSL", "DK01": "DCODE", "FI01": "DCVAN", "DE01": "DCHAM", "PL01": "DCHAM"}


def store_plan(reg):
    """(store_id, trade account, city, store name, format) for every sales.retail_store row."""
    if "store_plan" in reg.ctx:
        return reg.ctx["store_plan"]
    pool = reg.pools["sales.retail_store"]
    rnd = reg.rng("sales.retail_store", "plan")
    slots = []
    for t in world.RETAIL_BANNERS:
        slots += [t] * _STORES_PER_TIER[t["tier"]]
    plan, used = [], set()
    for i, sid in enumerate(pool):
        t = slots[i % len(slots)]
        cities = world.CITIES[t["country"]]
        for _ in range(20):
            c = rnd.choice(cities)
            name = "%s %s %s" % (t["dba"], c[0], rnd.choice(_STORE_SUFFIX[t["country"]]))
            if name not in used:
                break
        used.add(name)
        plan.append((sid, t, c, name, rnd.choice(_FORMAT[t["channel"]])))
    reg.ctx["store_plan"] = plan
    reg.ctx["store_by_id"] = dict((p[0], p) for p in plan)
    return plan


def _retail_store(reg):
    plan = store_plan(reg)

    def f(i, rnd):
        sid, t, c, name, fmt = plan[i]
        return {"_country": t["country"], "trade_account_id": reg.ctx["trade_id"][t["key"]],
                "banner_name": t["dba"], "store_name": name, "store_format": fmt,
                "store_tier": "tier_%s" % t["tier"][5], "store_number": "%s-%04d" % (t["key"][:4], 101 + i),
                "distribution_facility_id": reg.ctx["dc_id"][_DC_OF_COMPANY[t["company"]]],
                "store_phone": engine.phone(t["country"], rnd), "vmi_enabled_flag": t["tier"] == "tier_1_national",
                "store_size_sq_ft": {"hypermarket": 85000, "supermarket": 25000, "neighbourhood": 9000,
                                     "convenience": 2500, "discount": 12000, "specialty": 3500,
                                     "drugstore": 4500, "pharmacy": 3000}[fmt] + rnd.randint(-15, 15) * 100}
    return f


def _pos_transaction(reg):
    plan = store_plan(reg)
    sku_ids = reg.ctx["sku_id"]

    def f(i, rnd):
        sid, t, c, name, fmt = plan[rnd.randrange(len(plan))]
        mix = t["mix"]
        cats = ["FOOD", "BEVERAGE", "PERSONAL_CARE"]
        cat = rnd.choices(cats, weights=[m + 0.001 for m in mix])[0]
        sku = rnd.choice([s for s in world.SKUS if s["category"] == cat and s["season"] is None])
        cur = world.COUNTRY_CCY[t["country"]]
        price = (sku["rsp_eur"] / D(str(world.FX_BASE[cur]))).quantize(D("0.01"))
        units = D(rnd.randint(4, 180))
        promo = rnd.random() < 0.22
        disc = (price * units * D("0.20")).quantize(D("0.01")) if promo else D("0.00")
        day = world.TXN_START + datetime.timedelta(days=rnd.randint(0, (world.TXN_END - world.TXN_START).days))
        week_end = day + datetime.timedelta(days=6 - day.weekday())
        return {"_country": t["country"], "_anchor": datetime.datetime.combine(day, datetime.time(21, 0)),
                "retail_store_id": sid, "trade_account_id": reg.ctx["trade_id"][t["key"]],
                "retailer_name": t["dba"], "store_name": name, "store_city": c[0], "store_country_code": t["country"],
                "store_state_province": c[1], "store_postal_code": engine.postal_code(c[4], rnd), "store_format": fmt,
                "market_name": "%s %s" % (world.COUNTRY_NAMES[t["country"]], t["channel"].replace("_", " ")),
                "sku_id": sku_ids[sku["code"]], "sku": sku["code"], "product_description": sku["full_name"],
                "gtin": sku["gtin"], "ean": sku["gtin"], "upc": None, "currency_code": cur,
                "retail_selling_price": price, "units_sold": units, "discount_amount": disc,
                "extended_retail_value": (price * units - disc).quantize(D("0.01")), "promotional_flag": promo,
                "transaction_date": day, "week_ending_date": week_end, "unit_of_measure": "EA"}
    return f


def _account_contact(reg):
    accounts = world.TRADE

    def f(i, rnd):
        t = accounts[i % len(accounts)]
        return {"_country": t["country"], "trade_account_id": reg.ctx["trade_id"][t["key"]],
                "language_preference": t["country"]}
    return f


def _shipment(reg):
    plan = store_plan(reg)

    def f(i, rnd):
        if rnd.random() < 0.6:
            sid, t, c, name, fmt = plan[rnd.randrange(len(plan))]
            carrier = texts.ROAD_CARRIER[t["country"]]
            return {"_country": t["country"], "retail_store_id": sid, "trade_account_id": reg.ctx["trade_id"][t["key"]],
                    "carrier_code": carrier, "carrier_name": texts.CARRIER_NAMES[carrier],
                    "destination_type": "retail_store", "destination_name": name, "destination_city": c[0],
                    "destination_country_code": t["country"], "destination_state_province": c[1],
                    "destination_postal_code": engine.postal_code(c[4], rnd)}
        t = rnd.choice(world.TRADE)
        c = world.city(t["country"], t["hq"])
        carrier = texts.ROAD_CARRIER[t["country"]]
        return {"_country": t["country"], "trade_account_id": reg.ctx["trade_id"][t["key"]],
                "carrier_code": carrier, "carrier_name": texts.CARRIER_NAMES[carrier],
                "destination_type": "distribution_center", "destination_name": "%s central warehouse %s" % (t["dba"], c[0]),
                "destination_city": c[0], "destination_country_code": t["country"],
                "destination_state_province": c[1], "destination_postal_code": engine.postal_code(c[4], rnd)}
    return f


HOOKS = {"sales.retail_store": _retail_store, "sales.pos_transaction": _pos_transaction,
         "sales.account_contact": _account_contact, "distribution.shipment": _shipment}


def fixed_fn(reg, fqn):
    hook = HOOKS.get(fqn)
    return hook(reg) if hook else None
